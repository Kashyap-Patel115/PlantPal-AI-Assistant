def check_ollama_status():
    """
    Check if the local Ollama daemon is reachable and whether smollm2:360m is ready.
    Returns: (is_online: bool, message: str)
    """
    try:
        res = requests.get(f"{OLLAMA_API_URL}/api/tags", timeout=3)
        if res.status_code == 200:
            models = res.json().get("models", [])
            has_model = any(m.get("name", "").startswith("smollm2:360m") for m in models)
            if has_model:
                return True, "Ollama is running with SmolLM2 360M ready."
            return True, "Ollama is running, but SmolLM2 360M is not yet pulled."
        return False, f"Ollama returned HTTP status {res.status_code}."
    except requests.exceptions.RequestException as e:
        return False, f"Cannot connect to Ollama at {OLLAMA_API_URL} ({str(e)})."


def get_fallback_answer(query):
    """
    Match query keywords against verified gardening tips.
    Returns a dict clearly identifying this as fallback advice.
    """
    lower_q = query.lower()
    for item in FALLBACK_KNOWLEDGE:
        if any(kw in lower_q for kw in item["keywords"]):
            return {
                "answer": item["advice"],
                "topic": item["topic"],
                "source": "curated_gardening_guide",
                "is_fallback": True,
                "model_name": None,
                "note": "Offline Fallback: Local AI was not reached. Showing verified gardening handbook advice."
            }

    # Default fallback if no specific keywords matched
    return {
        "answer": (
            "For general home gardening success: ensure your pot has drainage holes, use bright indirect daylight, "
            "and only water when the top 1–2 inches of soil feel dry. Browse the Plant Library in PlantPal for plant-specific care!"
        ),
        "topic": "General Plant Care Rule",
        "source": "curated_gardening_guide",
        "is_fallback": True,
        "model_name": None,
        "note": "Offline Fallback: Local AI was not reached. Showing verified gardening handbook advice."
    }


def ask_gardening_assistant(user_question):
    """
    Ask a question to SmolLM2 360M running via Ollama.
    Falls back gracefully if Ollama is offline or times out.
    """
    clean_question = user_question.strip()
    if not clean_question:
        return {
            "answer": "Please ask a question about your plants!",
            "is_fallback": True,
            "source": "client_validation",
            "topic": "Empty Query"
        }

    # System instruction tailored for SmolLM2 360M lightweight capabilities
    prompt_payload = {
        "model": MODEL_NAME,
        "prompt": (
            "You are PlantPal AI, a friendly, expert gardening mentor. "
            "Answer this gardening question clearly, helpfully, and concisely in 2 to 3 sentences.\n\n"
            f"Question: {clean_question}\n\n"
            "Answer:"
        ),
        "stream": False,
        "options": {
            "temperature": 0.4,
            "top_p": 0.9,
            "num_predict": 150
        }
    }

    try:
        response = requests.post(
            f"{OLLAMA_API_URL}/api/generate",
            json=prompt_payload,
            timeout=REQUEST_TIMEOUT
        )

        if response.status_code == 200:
            result = response.json()
            raw_text = result.get("response", "").strip()

            if raw_text:
                return {
                    "answer": raw_text,
                    "is_fallback": False,
                    "source": "smollm2:360m",
                    "model_name": MODEL_NAME,
                    "topic": "AI Response",
                    "note": f"Generated locally by {MODEL_NAME} via Ollama"
                }

        # If model returned empty or non-200, use fallback
        fallback = get_fallback_answer(clean_question)
        fallback["reason"] = f"Model response code {response.status_code}"
        return fallback

    except requests.exceptions.Timeout:
        logger.warning("Ollama query timed out. Using fallback.")
        fallback = get_fallback_answer(clean_question)
        fallback["reason"] = "Ollama query timed out after 25s."
        return fallback

    except requests.exceptions.RequestException as e:
        logger.warning(f"Ollama connection error: {e}. Using fallback.")
        fallback = get_fallback_answer(clean_question)
        fallback["reason"] = "Could not reach local Ollama API."
        return fallback
